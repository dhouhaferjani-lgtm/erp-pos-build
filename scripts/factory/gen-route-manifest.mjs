#!/usr/bin/env node
// Route manifest generator (dark-factory page-coverage, spec §4).
// Parses the React Router route registries with the TypeScript compiler API
// and emits scripts/factory/manifests/routes-{web,pos}.yaml.
//
// Usage:
//   node scripts/factory/gen-route-manifest.mjs            # (re)write manifests
//   node scripts/factory/gen-route-manifest.mjs --out DIR  # write to DIR instead
//   node scripts/factory/gen-route-manifest.mjs --check    # exit 1 on drift
//
// Manifest row: { path, component, module_gate, permission }.
// module_gate = nearest <ModuleGuard module="X">, else nearest
// <RequirePermission moduleKey="X"> (A4: ModuleGuard wins when both wrap).
// Catch-all routes (path containing '*') are skipped; index routes emit at
// the parent path; routes with child <Route>s are layout routes (not emitted).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'
import { parseArgs } from 'node:util'
import { dump as yamlDump } from 'js-yaml'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
// A5: typescript is NOT a root dependency — resolve it from apps/web.
const ts = createRequire(join(repoRoot, 'apps/web/package.json'))('typescript')

const HEADER =
  '# GENERATED by gen-route-manifest.mjs — do not edit; run: node scripts/factory/gen-route-manifest.mjs\n'

/** Pure wrappers we look through when resolving a route's component. */
const WRAPPERS = new Set([
  'SuspenseWrapper', 'Suspense', 'RequireAuth', 'RequireAdminAuth',
  'ModuleGuard', 'RequirePermission', 'ThemeProvider', 'ErrorBoundary',
])

const SOURCES = {
  web: ['apps/web/src/routes/index.tsx'],
  pos: ['apps/pos/src/App.tsx', 'apps/pos/src/components/AppShell.tsx'],
}

// A3: phase-gated non-<Route> POS screens. Source: apps/pos/src/App.tsx
// render phases (App.tsx:66-253 at spec time) — AppRouter's conditional
// returns before AppShell mounts, plus the two dedicated-window pages.
const POS_PHASE_SCREENS = [
  { screen: 'auth-loading', route: null },
  { screen: 'login', route: null },
  { screen: 'company-select', route: null },
  { screen: 'terminal-setup', route: null },
  { screen: 'pin-setup', route: null },
  { screen: 'pin-entry', route: null },
  { screen: 'bootstrap-error', route: null },
  { screen: 'customer-display', route: '/customer-display' },
  { screen: 'theme-preview', route: '/theme-preview' },
]

const tagName = (node) => {
  const t = ts.isJsxElement(node) ? node.openingElement.tagName : node.tagName
  return t.getText()
}

const isJsxTag = (node) => ts.isJsxElement(node) || ts.isJsxSelfClosingElement(node)

/** String value of a JSX attribute, or undefined (non-literal → raw text). */
function attrValue(node, name) {
  const attrs = (ts.isJsxElement(node) ? node.openingElement : node).attributes.properties
  for (const a of attrs) {
    if (!ts.isJsxAttribute(a) || a.name.getText() !== name) continue
    if (a.initializer === undefined) return true // bare attribute (e.g. index)
    if (ts.isStringLiteral(a.initializer)) return a.initializer.text
    if (ts.isJsxExpression(a.initializer) && a.initializer.expression !== undefined) {
      const e = a.initializer.expression
      return ts.isStringLiteral(e) ? e.text : e.getText()
    }
  }
  return undefined
}

/** First JSX element found under `node` (depth-first), or null. */
function firstJsx(node) {
  if (node === undefined || node === null) return null
  if (isJsxTag(node)) return node
  let found = null
  node.forEachChild((c) => {
    if (found === null) found = firstJsx(c)
  })
  return found
}

/**
 * Resolve a Route's element expression: walk through guard/wrapper layers,
 * collecting guard attributes, until the first non-wrapper component.
 * Returns { component, moduleGuard, moduleKey, permission } (all nullable).
 */
function resolveElement(exprNode) {
  const out = { component: null, moduleGuard: null, moduleKey: null, permission: null }
  let el = firstJsx(exprNode)
  while (el !== null) {
    const name = tagName(el)
    if (!WRAPPERS.has(name)) {
      out.component = name
      return out
    }
    if (name === 'ModuleGuard') {
      const m = attrValue(el, 'module')
      if (typeof m === 'string') out.moduleGuard = m
    }
    if (name === 'RequirePermission') {
      const mk = attrValue(el, 'moduleKey')
      if (typeof mk === 'string') out.moduleKey = mk
      const p = attrValue(el, 'permission')
      if (typeof p === 'string') out.permission = p
    }
    el = ts.isJsxElement(el)
      ? el.children.map((c) => firstJsx(c)).find((c) => c !== null) ?? null
      : null // self-closing wrapper: nothing to descend into
  }
  return out
}

const joinPath = (parent, seg) => {
  if (seg.startsWith('/')) return seg
  if (parent === '' || parent === '/') return `/${seg}`
  return `${parent}/${seg}`
}

/**
 * Extract route rows from a routes source file.
 * @param {string} sourceText TSX source
 * @param {string} filePath used for TS diagnostics only
 * @returns {Array<{path: string, component: string|null, module_gate: string|null, permission: string|null}>}
 */
export function extractRoutes(sourceText, filePath) {
  const sf = ts.createSourceFile(filePath, sourceText, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX)
  const routes = []

  // ctx: { path, moduleGuard, moduleKey, permission } inherited from ancestors.
  function visitRoute(node, ctx) {
    const pathAttr = attrValue(node, 'path')
    const isIndex = attrValue(node, 'index') !== undefined
    let routePath = null
    if (typeof pathAttr === 'string') routePath = joinPath(ctx.path, pathAttr)
    else if (isIndex) routePath = ctx.path === '' ? '/' : ctx.path

    const el = { moduleGuard: null, moduleKey: null, permission: null, component: null }
    const attrs = (ts.isJsxElement(node) ? node.openingElement : node).attributes.properties
    for (const a of attrs) {
      if (ts.isJsxAttribute(a) && a.name.getText() === 'element'
          && a.initializer !== undefined && ts.isJsxExpression(a.initializer)) {
        Object.assign(el, resolveElement(a.initializer.expression))
      }
    }

    const childCtx = {
      path: routePath ?? ctx.path,
      moduleGuard: el.moduleGuard ?? ctx.moduleGuard,
      moduleKey: el.moduleKey ?? ctx.moduleKey,
      permission: el.permission ?? ctx.permission,
    }

    const childRoutes = collectChildRoutes(node)
    if (childRoutes.length > 0) {
      for (const c of childRoutes) visitRoute(c, childCtx)
      return // layout route: rendered only via children
    }
    if (routePath === null || routePath.includes('*')) return
    routes.push({
      path: routePath,
      component: el.component,
      module_gate: childCtx.moduleGuard ?? childCtx.moduleKey,
      permission: childCtx.permission,
    })
  }

  /** Direct-descendant <Route> elements under a node (not crossing Routes). */
  function collectChildRoutes(node) {
    const found = []
    const children = ts.isJsxElement(node) ? node.children : []
    const scan = (n) => {
      if (isJsxTag(n) && tagName(n) === 'Route') {
        found.push(n)
        return
      }
      n.forEachChild(scan)
    }
    for (const c of children) scan(c)
    return found
  }

  const walk = (node) => {
    if (isJsxTag(node) && tagName(node) === 'Routes') {
      for (const c of collectChildRoutes(node)) {
        visitRoute(c, { path: '', moduleGuard: null, moduleKey: null, permission: null })
      }
      return
    }
    node.forEachChild(walk)
  }
  walk(sf)

  const seen = new Set()
  return routes
    .filter((r) => (seen.has(r.path) ? false : (seen.add(r.path), true)))
    .sort((a, b) => a.path.localeCompare(b.path))
}

/** Build the manifest document for one app. */
export function buildManifest(app, readFile = (p) => readFileSync(join(repoRoot, p), 'utf8')) {
  const routes = []
  const seen = new Set()
  for (const src of SOURCES[app]) {
    for (const r of extractRoutes(readFile(src), src)) {
      if (seen.has(r.path)) continue
      seen.add(r.path)
      routes.push(r)
    }
  }
  routes.sort((a, b) => a.path.localeCompare(b.path))
  const doc = { app, sources: SOURCES[app], routes }
  if (app === 'pos') doc.phase_screens = POS_PHASE_SCREENS
  return doc
}

export function manifestYaml(app) {
  return HEADER + yamlDump(buildManifest(app), { lineWidth: 120 })
}

const isMain = process.argv[1] !== undefined
  && resolve(process.argv[1]) === fileURLToPath(import.meta.url)

if (isMain) {
  const { values } = parseArgs({
    args: process.argv.slice(2),
    options: { out: { type: 'string' }, check: { type: 'boolean' } },
  })
  const outDir = values.out !== undefined
    ? resolve(values.out)
    : join(repoRoot, 'scripts/factory/manifests')
  let drift = false
  for (const app of Object.keys(SOURCES)) {
    const file = join(outDir, `routes-${app}.yaml`)
    const fresh = manifestYaml(app)
    if (values.check === true) {
      const committed = existsSync(file) ? readFileSync(file, 'utf8') : ''
      if (committed !== fresh) {
        console.error(`DRIFT: ${file} is out of date`)
        drift = true
      }
      continue
    }
    mkdirSync(outDir, { recursive: true })
    writeFileSync(file, fresh)
    const doc = buildManifest(app)
    console.log(`wrote ${file} (${doc.routes.length} routes${app === 'pos' ? `, ${doc.phase_screens.length} phase screens` : ''})`)
  }
  if (drift) {
    console.error('Route manifest drift — run: node scripts/factory/gen-route-manifest.mjs && commit the manifests')
    process.exit(1)
  }
}
